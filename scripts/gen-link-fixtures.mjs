// Generates the signed-link test fixtures used by the Shop and Stories tests.
//
// AssemblyScript tests cannot sign, so this script signs with fixed TEST
// link keys and writes the signatures into small .ts files the tests import.
// The keys are derived from public strings. They are worthless outside tests.
//
//   node scripts/gen-link-fixtures.mjs
//
// The message formats here MUST match Shop.promoDigest and Stories.inviteDigest:
//   promo:  sha256("swarmtales/promo/v1"  || shop    (25) || campaign id (8, BE) || wallet (25))
//   invite: sha256("swarmtales/invite/v1" || stories (25) || story id (8, BE) || invite id (8, BE) || wallet (25))

import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { Signer, utils } = require("koilib");

const SHOP = "1MRxjnjFDhZfjtjgpxBNczsMGVEtYqfFyS";
const STORIES = "16adhn5XjJDJzs4oPv3MxnQuRpqv7PCJnt";
const ACCOUNTS = [
  "1D7nRvrRgzCg9kYBwhPH3j3Gs6SmsRg3Wq", // 0 ALICE
  "1NJrBLUNiGRU66FNu1VmaTNsm8qs7ADXyf", // 1 BOB
  "1NRNShd6oHh1JCxfbnWj47PrgqvqeyK7w1", // 2 CARA
  "1PJLazQ9eg25WRsBbcgVfc9ng2cR1cRT52", // 3 MALLORY
];
const KEYS = 4;
const IDS = 3;

const sha = (b) => createHash("sha256").update(b).digest();
const keys = [];
for (let k = 0; k < KEYS; k++) {
  keys.push(new Signer({ privateKey: sha(Buffer.from("swarmtales-test-link-" + k)).toString("hex") }));
}
const addr = (a) => Buffer.from(utils.decodeBase58(a));
const u64 = (n) => {
  const b = Buffer.alloc(8);
  b.writeBigUInt64BE(BigInt(n));
  return b;
};

async function sign(signer, msg) {
  const sig = await signer.signHash(sha(msg));
  return Buffer.from(sig).toString("hex");
}

const header = `// GENERATED by scripts/gen-link-fixtures.mjs. Do not edit by hand.
// Test-only link keys derived from public strings. Worthless outside tests.
`;

const hexDecoder = `
function hex(s: string): Uint8Array {
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = <u8>parseInt(s.substr(i * 2, 2), 16);
  return out;
}
`;

async function promo() {
  const sigs = [];
  for (let k = 0; k < KEYS; k++)
    for (let c = 1; c <= IDS; c++)
      for (let a = 0; a < ACCOUNTS.length; a++)
        sigs.push(await sign(keys[k], Buffer.concat([Buffer.from("swarmtales/promo/v1"), addr(SHOP), u64(c), addr(ACCOUNTS[a])])));
  return header + `
export const LINK_ADDRESSES: string[] = [${keys.map((s) => JSON.stringify(s.getAddress())).join(", ")}];
const SIGS: string[] = [
${sigs.map((s) => "  " + JSON.stringify(s)).join(",\n")}
];
${hexDecoder}
// key 0..${KEYS - 1}, campaign 1..${IDS}, who 0 ALICE, 1 BOB, 2 CARA, 3 MALLORY
export function promoSig(key: i32, campaign: i32, who: i32): Uint8Array {
  return hex(SIGS[(key * ${IDS} + (campaign - 1)) * ${ACCOUNTS.length} + who]);
}
`;
}

async function invite() {
  const sigs = [];
  for (let k = 0; k < KEYS; k++)
    for (let i = 1; i <= IDS; i++)
      for (let a = 0; a < ACCOUNTS.length; a++)
        sigs.push(await sign(keys[k], Buffer.concat([Buffer.from("swarmtales/invite/v1"), addr(STORIES), u64(1), u64(i), addr(ACCOUNTS[a])])));
  return header + `
export const LINK_ADDRESSES: string[] = [${keys.map((s) => JSON.stringify(s.getAddress())).join(", ")}];
const SIGS: string[] = [
${sigs.map((s) => "  " + JSON.stringify(s)).join(",\n")}
];
${hexDecoder}
// Story 1 only. key 0..${KEYS - 1}, invite 1..${IDS}, who 0 ALICE, 1 BOB, 2 CARA, 3 MALLORY
export function inviteSig(key: i32, invite: i32, who: i32): Uint8Array {
  return hex(SIGS[(key * ${IDS} + (invite - 1)) * ${ACCOUNTS.length} + who]);
}
`;
}

writeFileSync(new URL("../shop/assembly/__tests__/linkFixtures.ts", import.meta.url), await promo());
writeFileSync(new URL("../stories/assembly/__tests__/linkFixtures.ts", import.meta.url), await invite());
console.log("Wrote shop/assembly/__tests__/linkFixtures.ts and stories/assembly/__tests__/linkFixtures.ts");
